#!/usr/bin/env node

import bcrypt from "bcryptjs"
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"

const DEFAULT_OUT = "supabase/seed_test_users_dev.generated.sql"
const DEFAULT_ROUNDS = 10

const TEST_USERS = [
  {
    id: "10000000-0000-4000-8000-000000000001",
    email: "user@zoosmart.local",
    password: "Password123!",
    role: "user",
    status: "active",
    displayName: "ZooSmart User Test",
  },
  {
    id: "10000000-0000-4000-8000-000000000002",
    email: "operator@zoosmart.local",
    password: "Password123!",
    role: "operator",
    status: "active",
    displayName: "ZooSmart Operator Test",
  },
  {
    id: "10000000-0000-4000-8000-000000000003",
    email: "admin.comune@zoosmart.local",
    password: "Password123!",
    role: "public_admin",
    status: "active",
    displayName: "ZooSmart Comune Test",
  },
]

const args = parseArgs(process.argv.slice(2))
const isDevelopment = args.dev || process.env.NODE_ENV === "development"

if (!isDevelopment) {
  fail("Refusing to generate test users outside development. Use NODE_ENV=development or pass --dev.")
}

if (args.stdout && args.out) {
  fail("Use either --stdout or --out, not both.")
}

const rounds = parsePositiveInteger(args.rounds ?? String(DEFAULT_ROUNDS), "--rounds")
const outputPath = args.stdout ? null : args.out ?? DEFAULT_OUT

const usersWithHashes = await Promise.all(
  TEST_USERS.map(async (user) => ({
    ...user,
    passwordHash: await bcrypt.hash(user.password, rounds),
  })),
)

const sql = buildSql(usersWithHashes, rounds)

if (outputPath) {
  const absoluteOutputPath = path.resolve(process.cwd(), outputPath)
  await mkdir(path.dirname(absoluteOutputPath), { recursive: true })
  await writeFile(absoluteOutputPath, sql, "utf8")
  console.error(`Generated ${outputPath}`)
} else {
  process.stdout.write(sql)
}

printDevelopmentCredentials(usersWithHashes)

function buildSql(users, roundsUsed) {
  const calls = users
    .map(
      (user) => `SELECT pg_temp.zoosmart_dev_upsert_test_user(
  ${sqlLiteral(user.id)}::uuid,
  ${sqlLiteral(user.email)},
  ${sqlLiteral(user.passwordHash)},
  ${sqlLiteral(user.role)},
  ${sqlLiteral(user.status)},
  ${sqlLiteral(user.displayName)}
);`,
    )
    .join("\n\n")

  return `/*
  ZooSmart development test users seed.

  Generated by scripts/seed-test-users.mjs with bcryptjs (${roundsUsed} rounds).
  Development only. Plaintext demo passwords are not stored in this SQL file.

  Run after the ZooSmart migrations, including 20260527120000_sprint2.sql.
*/

begin;

create or replace function pg_temp.zoosmart_dev_upsert_email_identity(
  p_user_id uuid,
  p_email text,
  p_display_name text
)
returns void
language plpgsql
as $$
declare
  v_identity_data jsonb;
  v_has_provider_id boolean;
  v_id_type text;
begin
  if to_regclass('auth.identities') is null then
    return;
  end if;

  v_identity_data := jsonb_build_object(
    'sub', p_user_id::text,
    'email', p_email,
    'email_verified', true,
    'phone_verified', false,
    'display_name', p_display_name
  );

  select exists (
    select 1
    from information_schema.columns
    where table_schema = 'auth'
      and table_name = 'identities'
      and column_name = 'provider_id'
  )
  into v_has_provider_id;

  if v_has_provider_id then
    insert into auth.identities (
      provider_id,
      user_id,
      identity_data,
      provider,
      last_sign_in_at,
      created_at,
      updated_at
    )
    values (
      p_user_id::text,
      p_user_id,
      v_identity_data,
      'email',
      now(),
      now(),
      now()
    )
    on conflict (provider_id, provider) do update
    set user_id = excluded.user_id,
        identity_data = excluded.identity_data,
        updated_at = now();
    return;
  end if;

  select data_type
  into v_id_type
  from information_schema.columns
  where table_schema = 'auth'
    and table_name = 'identities'
    and column_name = 'id';

  if v_id_type = 'uuid' then
    insert into auth.identities (
      id,
      user_id,
      identity_data,
      provider,
      last_sign_in_at,
      created_at,
      updated_at
    )
    values (
      p_user_id,
      p_user_id,
      v_identity_data,
      'email',
      now(),
      now(),
      now()
    )
    on conflict (id) do update
    set user_id = excluded.user_id,
        identity_data = excluded.identity_data,
        updated_at = now();
  else
    insert into auth.identities (
      id,
      user_id,
      identity_data,
      provider,
      last_sign_in_at,
      created_at,
      updated_at
    )
    values (
      p_user_id::text,
      p_user_id,
      v_identity_data,
      'email',
      now(),
      now(),
      now()
    )
    on conflict (id) do update
    set user_id = excluded.user_id,
        identity_data = excluded.identity_data,
        updated_at = now();
  end if;
end;
$$;

create or replace function pg_temp.zoosmart_dev_upsert_test_user(
  p_default_id uuid,
  p_email text,
  p_password_hash text,
  p_role text,
  p_status text,
  p_display_name text
)
returns void
language plpgsql
as $$
declare
  v_user_id uuid;
begin
  if p_role not in ('user', 'operator', 'public_admin') then
    raise exception 'invalid ZooSmart role: %', p_role;
  end if;

  if p_status not in ('active', 'suspended', 'blocked') then
    raise exception 'invalid ZooSmart profile status: %', p_status;
  end if;

  select id
  into v_user_id
  from auth.users
  where lower(email) = lower(p_email)
  order by created_at asc
  limit 1;

  if v_user_id is null then
    select id
    into v_user_id
    from auth.users
    where id = p_default_id
    limit 1;
  end if;

  if v_user_id is null then
    v_user_id := p_default_id;

    insert into auth.users (
      instance_id,
      id,
      aud,
      role,
      email,
      encrypted_password,
      email_confirmed_at,
      confirmation_sent_at,
      raw_app_meta_data,
      raw_user_meta_data,
      is_super_admin,
      created_at,
      updated_at
    )
    values (
      '00000000-0000-0000-0000-000000000000',
      v_user_id,
      'authenticated',
      'authenticated',
      lower(p_email),
      p_password_hash,
      now(),
      now(),
      jsonb_build_object('provider', 'email', 'providers', array['email'], 'zoosmart_role', p_role),
      jsonb_build_object('display_name', p_display_name, 'role', p_role, 'status', p_status),
      false,
      now(),
      now()
    );
  else
    update auth.users
    set aud = 'authenticated',
        role = 'authenticated',
        email = lower(p_email),
        encrypted_password = p_password_hash,
        email_confirmed_at = coalesce(email_confirmed_at, now()),
        confirmation_sent_at = coalesce(confirmation_sent_at, now()),
        raw_app_meta_data = coalesce(raw_app_meta_data, '{}'::jsonb)
          || jsonb_build_object('provider', 'email', 'providers', array['email'], 'zoosmart_role', p_role),
        raw_user_meta_data = coalesce(raw_user_meta_data, '{}'::jsonb)
          || jsonb_build_object('display_name', p_display_name, 'role', p_role, 'status', p_status),
        updated_at = now()
    where id = v_user_id;
  end if;

  perform pg_temp.zoosmart_dev_upsert_email_identity(v_user_id, lower(p_email), p_display_name);

  insert into public.profiles (
    id,
    email,
    display_name,
    role,
    status,
    created_at,
    updated_at
  )
  values (
    v_user_id,
    lower(p_email),
    p_display_name,
    p_role,
    p_status,
    now(),
    now()
  )
  on conflict (id) do update
  set email = excluded.email,
      display_name = excluded.display_name,
      role = excluded.role,
      status = excluded.status,
      updated_at = now();
end;
$$;

${calls}

commit;

select
  p.role,
  p.email,
  p.status,
  u.email_confirmed_at is not null as email_confirmed,
  u.raw_user_meta_data->>'role' as jwt_user_metadata_role,
  u.raw_app_meta_data->>'zoosmart_role' as jwt_app_metadata_zoosmart_role
from public.profiles p
join auth.users u on u.id = p.id
where p.email in (${users.map((user) => sqlLiteral(user.email)).join(", ")})
order by case p.role
  when 'user' then 1
  when 'operator' then 2
  when 'public_admin' then 3
  else 4
end;
`
}

function printDevelopmentCredentials(users) {
  console.error("ZooSmart development test credentials:")
  for (const user of users) {
    console.error(`- ${user.role}: ${user.email} / ${user.password}`)
  }
}

function parseArgs(rawArgs) {
  const parsed = {
    dev: false,
    out: null,
    rounds: null,
    stdout: false,
  }

  for (let index = 0; index < rawArgs.length; index += 1) {
    const arg = rawArgs[index]

    if (arg === "--dev") {
      parsed.dev = true
      continue
    }

    if (arg === "--stdout") {
      parsed.stdout = true
      continue
    }

    if (arg === "--out") {
      index += 1
      if (!rawArgs[index]) fail("Missing value for --out.")
      parsed.out = rawArgs[index]
      continue
    }

    if (arg === "--rounds") {
      index += 1
      if (!rawArgs[index]) fail("Missing value for --rounds.")
      parsed.rounds = rawArgs[index]
      continue
    }

    fail(`Unknown argument: ${arg}`)
  }

  return parsed
}

function parsePositiveInteger(value, label) {
  const parsed = Number.parseInt(value, 10)
  if (!Number.isInteger(parsed) || parsed <= 0) {
    fail(`${label} must be a positive integer.`)
  }
  return parsed
}

function sqlLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`
}

function fail(message) {
  console.error(message)
  process.exit(1)
}
